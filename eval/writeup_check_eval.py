"""
Offline evaluation of the write-up quality check. No LLM, no network, no key.

For each labelled submission it runs check_writeup_quality on the README and
compares the flag to the author's label ('filler' true/false). It reports the
confusion matrix and every individual call, so a reader can see which honest
submissions were wrongly flagged and which filler ones were missed.

    python eval/writeup_check_eval.py \
        --subs data/submissions --labels data/writeup_labels_dev.json --name dev
    python eval/writeup_check_eval.py \
        --subs data/submissions_heldout --labels data/writeup_labels_heldout.json --name held-out

Writes eval/WRITEUP_CHECK_<name>.md.
"""
import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from agent.panelassist.writeup import check_writeup_quality


def evaluate(subs_dir: str, labels: dict) -> dict:
    rows, tp, fp, tn, fn = [], 0, 0, 0, 0
    for slug in sorted(labels):
        path = os.path.join(subs_dir, slug, "README.md")
        if not os.path.exists(path):
            rows.append({"slug": slug, "missing": True})
            continue
        with open(path, encoding="utf-8") as f:
            res = check_writeup_quality(f.read())
        flagged = not res["passed"]
        truth = bool(labels[slug]["filler"])
        tp += int(flagged and truth)
        fp += int(flagged and not truth)
        tn += int((not flagged) and (not truth))
        fn += int((not flagged) and truth)
        rows.append({"slug": slug, "label_filler": truth, "flagged": flagged,
                     "signals": [s["name"] for s in res["signals"]], "detail": res["detail"]})
    n = tp + fp + tn + fn
    return {
        "n": n, "true_positive": tp, "false_positive": fp, "true_negative": tn, "false_negative": fn,
        "recall": round(tp / (tp + fn), 3) if (tp + fn) else None,
        "false_alarm_rate": round(fp / (fp + tn), 3) if (fp + tn) else None,
        "precision": round(tp / (tp + fp), 3) if (tp + fp) else None,
        "rows": rows,
    }


def render(name: str, r: dict, note: str) -> str:
    L = [f"# Write-up quality check - {name} set\n", note, "",
         f"Cases: {r['n']}. Check is deterministic; this file is regenerated by "
         f"`python eval/writeup_check_eval.py` and needs no key.", "",
         "| | Labelled filler | Labelled not filler |", "|---|---|---|",
         f"| **Flagged** | {r['true_positive']} (true positive) | {r['false_positive']} (false alarm) |",
         f"| **Not flagged** | {r['false_negative']} (missed) | {r['true_negative']} (true negative) |", "",
         f"Recall {r['recall']}, false-alarm rate {r['false_alarm_rate']}, precision {r['precision']}. "
         f"With n={r['n']} one case moves these a lot; treat them as a smoke test, not a benchmark.", "",
         "## Every case", "", "| Submission | Labelled filler | Flagged | Signals that fired |", "|---|---|---|---|"]
    for row in r["rows"]:
        if row.get("missing"):
            L.append(f"| {row['slug']} | - | - | README missing |")
        else:
            L.append(f"| {row['slug']} | {row['label_filler']} | {row['flagged']} | {', '.join(row['signals']) or '-'} |")
    L.append("")
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--subs", required=True)
    ap.add_argument("--labels", required=True)
    ap.add_argument("--name", required=True)
    ap.add_argument("--note", default="")
    args = ap.parse_args()
    with open(args.labels, encoding="utf-8") as f:
        labels = json.load(f)["labels"]
    r = evaluate(args.subs, labels)
    safe = args.name.replace(" ", "_")
    out_md = f"eval/WRITEUP_CHECK_{safe}.md"
    out_json = f"eval/writeup_check_{safe}.json"
    with open(out_md, "w", encoding="utf-8") as f:
        f.write(render(args.name, r, args.note))
    with open(out_json, "w", encoding="utf-8") as f:
        json.dump(r, f, indent=2)
    print(render(args.name, r, args.note))


if __name__ == "__main__":
    main()
